def _rng(*parts):
    seed = '|'.join(str(part) for part in parts)
    return random.Random(seed)


def build_sections(unit_name, filename=None):
    """A course's section breakdown: a curated, textbook-order profile for
    known subjects, or a generic 3-part shape as a fallback."""
    hint = f'（参考ファイル: {filename}）' if filename else ''
    template = UNIT_SECTION_PROFILES.get(unit_name.strip(), DEFAULT_SECTION_TEMPLATE)
    return [
        {'title': title, 'content': content.format(name=unit_name) + hint}
        for title, content in template
    ]


def _linear_equation(rng):
    a = rng.randint(2, 9)
    x = rng.choice([v for v in range(-8, 13) if v != 0])
    b = rng.randint(-15, 15)
    c = a * x + b
    return a, b, c, x


def _word_problem_equation(rng):
    a = rng.randint(2, 9)
    x = rng.randint(1, 12)
    b = rng.randint(1, 15)
    c = a * x + b
    return a, b, c, x


def _equation_text(a, b, c):
    sign = '+' if b >= 0 else '-'
    return f'{a}x {sign} {abs(b)} = {c}'


def _word_problem_text(a, b, c):
    return (
        f'1冊{a}円のノートをx冊と、1個{b}円の消しゴムを1個買ったところ、'
        f'代金の合計は{c}円でした。ノートを何冊買ったか、xの値を求めてください。'
    )


def _is_word_problem_section(section):
    return '文章題' in section.title


def _equation_for(section, kind, salt=0):
    """The single source of truth for a (section, kind) pair's numbers —
    build_problem and build_hint both call this so they always agree.
    `salt=0` reproduces the exact seed used before duplicate-avoidance was
    added (so existing stored problems keep matching); salt=1,2,... give
    additional deterministic variants used only to dodge an exact-text
    repeat within a session — see build_unique_problem."""
    parts = (section.id, kind) if salt == 0 else (section.id, kind, salt)
    rng = _rng(*parts)
    if _is_word_problem_section(section):
        return _word_problem_equation(rng)
    return _linear_equation(rng)


def _ai_fallback_entry(section, *, kind, salt=0):
    """A subject-matched practice problem for AI failure/off-topic
    fallback (see AI_FALLBACK_PROBLEMS), or None if this unit's name isn't
    in the catalog. Chosen deterministically from section.id+kind (see
    _equation_for's `salt` note — salt=0 matches the original seed), the
    same pattern as _equation_for, so build_problem/judge_answer/
    diagnosis_question/etc. all agree on the same entry without needing to
    store which one was picked."""
    catalog = AI_FALLBACK_PROBLEMS.get(section.unit.name.strip())
    if not catalog:
        return None
    parts = (section.id, kind, 'ai_fallback') if salt == 0 else (section.id, kind, 'ai_fallback', salt)
    rng = _rng(*parts)
    return rng.choice(catalog['problems'])


def fallback_notes(section, *, kind, salt=0):
    """(correct_note, wrong_note) for the active fallback problem (see
    AI_FALLBACK_PROBLEMS), or (None, None) when no fallback applies —
    used by services._judge to pass subject-appropriate explanations to
    judge_answer instead of its linear-equation-specific defaults."""
    entry = _ai_fallback_entry(section, kind=kind, salt=salt)
    if entry is None:
        return None, None
    return entry['correct_note'], entry['wrong_note']


def looks_like_subject(section, text):
    """Heuristic sanity check — not a rigorous topic verifier. Only
    catches an AI-generated problem that shares no vocabulary at all with
    the unit's subject (e.g. AI degenerating into a generic algebra
    problem for an advanced course). A single keyword or the unit name
    itself appearing anywhere in the text is enough to pass; subjects with
    no fallback catalog entry are never flagged (nothing to check
    against)."""
    catalog = AI_FALLBACK_PROBLEMS.get(section.unit.name.strip())
    if not catalog:
        return True
    unit_name = section.unit.name.strip()
    return unit_name in text or any(term in text for term in catalog['keywords'])


def build_problem(section, *, kind, salt=0):
    """kind is 'first', 'transfer', or 'diagnostic' — distinct equations for
    the same section. A subject-matched fallback problem (see
    AI_FALLBACK_PROBLEMS) takes priority when this unit's name is in the
    catalog; otherwise sections titled with "文章題" get a word-problem
    phrasing of a linear equation, and everything else gets the bare
    equation. `salt` selects a deterministic variant — see
    _equation_for/_ai_fallback_entry and build_unique_problem."""
    fallback = _ai_fallback_entry(section, kind=kind, salt=salt)
    if fallback is not None:
        return fallback['problem'], fallback['answer']
    a, b, c, x = _equation_for(section, kind, salt=salt)
    if _is_word_problem_section(section):
        return _word_problem_text(a, b, c), x
    return _equation_text(a, b, c), x


MAX_PROBLEM_DEDUP_ATTEMPTS = 4


def build_unique_problem(section, *, kind, exclude=()):
    """Like build_problem, but tries a few deterministic variants (salt=0,
    1, 2, ...) to avoid exactly repeating a problem text already used
    elsewhere in this session (`exclude`). If every variant still collides
    — a small fixed catalog (AI_FALLBACK_PROBLEMS has 2 entries per
    subject) can genuinely run out — the last variant tried is returned
    anyway rather than looping forever; an occasional repeat once the pool
    is exhausted is an honest limit, not a bug."""
    exclude = set(exclude)
    result = None
    for salt in range(MAX_PROBLEM_DEDUP_ATTEMPTS):
        problem, value = build_problem(section, kind=kind, salt=salt)
        if problem not in exclude:
            return problem, value
        result = (problem, value)
    return result


def _extract_numbers(text):
    normalized = unicodedata.normalize('NFKC', text)
    return {
        float(n) if '.' in n else int(n)
        for n in re.findall(r'-?\d+(?:\.\d+)?', normalized)
    }


def judge_answer(*, answer, expected_value, correct_note=None, wrong_note=None):
    numbers = _extract_numbers(answer)
    is_correct = expected_value in numbers
    if is_correct:
        explanation = f'正解です！ {correct_note or f"x = {expected_value} で合っています。"}'
    else:
        explanation = f'不正解です。{wrong_note or "移項してxだけの形に整理できているか見直してみましょう。"}'
    return is_correct, explanation


def diagnosis_question(section, *, confidence=None):
    """confidence >= 4 (quadrant C: wrong but confident) points at a real
    misconception, so the question goes straight at the likely error.
    confidence <= 3 or unset (quadrant D: wrong and unsure) gets a softer,
    more exploratory question instead. Threshold matches
    mastery.CONFIDENT_THRESHOLD — kept as a local constant since this
    module stays dependency-free from the rest of the app.

    When a subject-matched fallback problem is active (see
    AI_FALLBACK_PROBLEMS), the wording switches to subject-neutral phrasing
    instead of the linear-equation-specific "移項"/"符号" language, which
    wouldn't make sense for e.g. a group theory or Fourier transform
    problem."""
    if _ai_fallback_entry(section, kind='first') is not None:
        if confidence is not None and confidence >= 4:
            return (
                'その解答にたどり着いたとき、どの公式や考え方を使いましたか？'
                '手順を振り返ってみましょう。',
                '公式の適用ミス',
            )
        return (
            'この問題を解くとき、どの公式やルールを使えばよいか、もう一度確認してみましょう。',
            '公式の適用ミス',
        )
    if confidence is not None and confidence >= 4:
        return (
            'その解答にたどり着いたとき、まず何を計算しましたか？符号はどのように'
            '扱いましたか？',
            '移項の符号ミス',
        )
    return (
        '移項して x の項を左辺に、定数を右辺に集めるとき、符号はどうなりますか？',
        '移項の符号ミス',
    )


def verification_question(section):
    if _ai_fallback_entry(section, kind='first') is not None:
        return 'なぜその答えになるのか、使った考え方や公式をあなたの言葉で説明してください。'
    return 'なぜ両辺から同じ数を引いても方程式が成り立ったままなのか、あなたの言葉で説明してください。'


def _generic_fallback_hint(entry, *, level):
    """Subject-neutral 5-level hint ladder used when a fallback problem
    (see AI_FALLBACK_PROBLEMS) is active — the equation-specific hints
    below ("移項"/符号 handling) wouldn't apply to an arbitrary subject."""
    hints = (
        '問題文をもう一度読んで、何を求められているか整理しましょう。',
        'この分野で使う基本的な公式や定理を思い出してみましょう。',
        '似たような例題を思い浮かべ、同じ手順で進めてみましょう。',
        '途中の計算を1つずつ書き出して、どこで止まっているか確認しましょう。',
        f"完全な解答のヒント: 答えは {entry['answer']} です。どの手順でこの値にたどり着けるか、"
        '公式に当てはめて振り返ってみましょう。',
    )
    return hints[level - 1]


def build_hint(*, section, level, kind='first', salt=0):
    """`salt` must match whichever variant was actually shown as the
    problem (see build_unique_problem) — otherwise level 5's answer
    reveal, or the worked example's numbers, could belong to a different
    variant than the one the learner is actually solving."""
    fallback = _ai_fallback_entry(section, kind=kind, salt=salt)
    if fallback is not None:
        return _generic_fallback_hint(fallback, level=level)
    a, b, c, x = _equation_for(section, kind, salt=salt)
    sign = '+' if b >= 0 else '-'
    example_a, example_b = a + 1, b - 2
    example_c = example_a * (x + 1) + example_b
    example_sign = '+' if example_b >= 0 else '-'
    step1_c = c - b
    first_hint = (
        f'まず、問題文から {a}x {sign} {abs(b)} = {c} の形の式を立てましょう。'
        if _is_word_problem_section(section)
        else 'まず、x を含む項を左辺に、数だけの項（定数）を右辺に集めましょう。'
    )
    hints = (
        first_hint,
        '項を移項するときは、符号（+/−）が反転することを思い出しましょう。',
        f'例えば {example_a}x {example_sign} {abs(example_b)} = {example_c} なら、まず両辺から{abs(example_b)}を'
        f'{"引いて" if example_b >= 0 else "足して"} {example_a}x = {example_c - example_b} にします。',
        f'この問題では、まず両辺から{abs(b)}を{"引いて" if b >= 0 else "足して"} {a}x = {step1_c} の形にします。'
        'そのあと両辺を係数で割ります。',
        f'完全な解答: {_equation_text(a, b, c)} → 両辺から{abs(b)}を{"引いて" if b >= 0 else "足して"} '
        f'{a}x = {step1_c} → 両辺を{a}で割って x = {x}。',
    )
    return hints[level - 1]


def review_recommendation(section):
    return (
        f'「{section.title}」の移項のルール（符号が反転すること）をもう一度確認してから、'
        '同じ形の一次方程式をいくつか練習してみましょう。'
    )


def diagnostic_level_feedback(correct_count, total):
    if total == 0:
        return 'この科目にはまだセクションがありません。科目にセクションが追加されると診断クイズが出題されます。'
    ratio = correct_count / total
    if ratio == 1:
        return (
            f'{total}問すべて正解でした。この科目の基礎はすでに身についているようです。'
            '発展的なセクションから取り組んでみましょう。'
        )
    if ratio >= 0.5:
        return (
            f'{total}問中{correct_count}問正解でした。理解度は「普通」です。'
            '間違えた問題に対応するセクションを優先的に復習しましょう。'
        )
    return (
        f'{total}問中{correct_count}問正解でした。理解度は「要復習」です。'
        '基礎のセクションから順番に進めることをおすすめします。'
    )


SHORT_TEACH_BACK_PROMPT = '今回の問題で一番重要だった考え方を、1〜2文で説明してください。'

TEACH_BACK_ANSWER_MIN_LENGTH = 10
TEACH_BACK_ANSWER_CONCEPT_TERMS = ('移項', '両辺', '符号', '方程式', '等式')


def teach_back_question(section, *, kind='first', misconception=''):
    """A concrete, concept-core follow-up question for Level 2 (Targeted)
    Teach-Back, grounded in the actual equation this learner just solved —
    not a request to restate the answer (see
    ai_prompts.TEACH_BACK_TARGETED_QUESTION_SYSTEM_PROMPT)."""
    a, b, c, _x = _equation_for(section, kind)
    sign = '+' if b >= 0 else '-'
    if '符号' in misconception:
        return (
            f'{a}x {sign} {abs(b)} = {c} を解くとき、{abs(b)}を移項すると符号が変わるのは'
            'なぜですか？あなたの言葉で説明してください。'
        )
    return (
        f'{a}x {sign} {abs(b)} = {c} の両辺から同じ数をひいても、方程式が成り立ったままなのは'
        'なぜですか？あなたの言葉で説明してください。'
    )


def evaluate_teach_back_answer(answer):
    """Non-AI fallback for judging a single short Teach-Back answer — a
    length + concept-language proxy, not real language understanding (same
    limitation as before, now scoped to one short answer instead of five
    long fields). A fluent-sounding answer without concept language isn't
    accepted as proof of understanding on its own."""
    text = answer.strip()
    if len(text) < TEACH_BACK_ANSWER_MIN_LENGTH:
        return (
            'PARTIAL_UNDERSTANDING',
            'もう少し具体的に、自分の言葉で説明してみましょう。',
            'この問題で、なぜその計算をしたのか、もう一度説明してみてください。',
        )
    if not any(term in text for term in TEACH_BACK_ANSWER_CONCEPT_TERMS):
        return (
            'PARTIAL_UNDERSTANDING',
            '関連する考え方（移項・両辺・符号など）に触れてみましょう。',
            'この問題を解くときに使った考え方を、もう一言説明してみてください。',
        )
    return 'CLEAR_UNDERSTANDING', '自分の言葉でしっかり説明できています。', ''


